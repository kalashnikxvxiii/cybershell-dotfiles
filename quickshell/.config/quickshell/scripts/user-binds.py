#!/usr/bin/env python3
"""The personal keybinds: ~/.config/hypr/user-binds.json, turned into lua/user-binds.lua.

  list                          the binds, as JSON
  check <keys> [own name]       prints the name of the bind already on <keys>, if any
  save <index|-1> <name> <keys> <command>
  remove <index>

keybindings-v2.lua is never touched. Saving and removing reload Hyprland.
"""
import json
import os
import re
import subprocess
import sys

HOME = os.path.expanduser("~/.config/hypr")
STORE = os.path.join(HOME, "user-binds.json")
LUA = os.path.join(HOME, "lua", "user-binds.lua")
SECTION = "MY BINDS"
KEYS_RE = re.compile(r"^((SUPER|CTRL|ALT|SHIFT) \+ )*[A-Za-z0-9_:]+$")
MOD_BITS = {"SHIFT": 1, "CTRL": 4, "ALT": 8, "SUPER": 64}


def fail(message):
    print(message, file=sys.stderr)
    sys.exit(1)


def load():
    try:
        with open(STORE) as f:
            return json.load(f)
    except FileNotFoundError:
        return []


def write_through(path, text):
    # The files are stow links: replacing the link itself would take them out of the dotfiles
    real = os.path.realpath(path)
    tmp = real + ".tmp"
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, real)


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def store(binds):
    lines = ["-- Generated by quickshell/scripts/user-binds.py from user-binds.json: don't edit by hand.\n"]
    for b in binds:
        note = b["command"].replace("|", " ")
        description = "%s|%s|%s" % (SECTION, b["name"], note)
        lines.append("hl.bind(%s, hl.dsp.exec_cmd(%s), { description = %s })\n"
                     % (lua_string(b["keys"]), lua_string(b["command"]), lua_string(description)))
    write_through(STORE, json.dumps(binds, indent=2) + "\n")
    write_through(LUA, "".join(lines))
    subprocess.run(["hyprctl", "reload"], stdout=subprocess.DEVNULL, check=False)


def split_keys(keys):
    parts = keys.split(" + ")
    return sum(MOD_BITS[m] for m in parts[:-1]), parts[-1].lower()


def check(keys, own):
    mask, key = split_keys(keys)
    out = subprocess.run(["hyprctl", "binds", "-j"], capture_output=True, text=True, check=True).stdout
    for b in json.loads(out):
        if b.get("submap") or b["modmask"] != mask or b["key"].lower() != key:
            continue
        parts = b.get("description", "").split("|")
        name = parts[1] if len(parts) == 3 else (b.get("description") or b["key"])
        if own and parts[0] == SECTION and name == own:
            continue
        print(name)
        return


def index_of(text, binds, allow_new):
    try:
        i = int(text)
    except ValueError:
        fail("bad index: " + text)
    if (allow_new and i == -1) or 0 <= i < len(binds):
        return i
    fail("bad index: " + text)


def main(args):
    cmd = args[0] if args else ""
    if cmd == "list":
        print(json.dumps(load()))
    elif cmd == "check" and len(args) in (2, 3):
        if not KEYS_RE.match(args[1]):
            fail("bad keys: " + args[1])
        check(args[1], args[2] if len(args) == 3 else "")
    elif cmd == "save" and len(args) == 5:
        _, index, name, keys, command = args
        if not name.strip() or "|" in name or "\n" in name:
            fail("the name can't be empty or contain |")
        if not KEYS_RE.match(keys):
            fail("bad keys: " + keys)
        if not command.strip() or "\n" in command:
            fail("the command can't be empty")
        binds = load()
        i = index_of(index, binds, True)
        entry = {"name": name.strip(), "keys": keys, "command": command.strip()}
        if i == -1:
            binds.append(entry)
        else:
            binds[i] = entry
        store(binds)
    elif cmd == "remove" and len(args) == 2:
        binds = load()
        del binds[index_of(args[1], binds, False)]
        store(binds)
    else:
        fail(__doc__)


if __name__ == "__main__":
    main(sys.argv[1:])
